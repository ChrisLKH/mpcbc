// Turns the bundled opencc-js Hong Kong → Simplified dictionaries into a PHP array for mpcbc-translations.
// Run: node scripts/build-t2s-data.mjs   (rerun after updating plugins/mpcbc-translations/opencc-js/t2cn.js)
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const plugin = new URL('../plugins/mpcbc-translations/', import.meta.url);
const { Locale } = require(new URL('opencc-js/t2cn.js', plugin).pathname.replace(/^\/(\w:)/, '$1'));
const config = Locale.configs.hk2s; // what Converter({ from: 'hk', to: 'cn' }) uses

// One dictionary: "src dst|src dst"; a later duplicate wins, as in opencc-js.
const dict = (d) => Object.fromEntries((typeof d === 'string' ? d.split('|').map((e) => e.split(' ')) : d).map(([k, v]) => [k, v]));
// A group: the first dictionary wins (opencc-js loads groups in reverse).
const group = (g) => Object.assign({}, ...g.slice().reverse().map(dict));

const [normalize] = config.normalizationChain;
const [step1, step2] = config.conversionChain;
const data = {
  normalize: group(normalize),
  // Segmentation: wrap each known phrase in \x1F so later steps cannot match across phrase edges.
  segments: Object.fromEntries(Object.keys(group(config.segmentation)).map((k) => [k, `\x1F${k}\x1F`])),
  step1: group(step1),
  step2: group(step2),
};

const php = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const arr = (o) => `array(\n${Object.entries(o).map(([k, v]) => `\t\t${php(k)} => ${php(v).replace(/\x1F/g, "' . \"\\x1F\" . '")},`).join('\n')}\n\t)`;
writeFileSync(new URL('t2s-data.php', plugin),
  `<?php\n// Generated by scripts/build-t2s-data.mjs from opencc-js (Apache-2.0, see opencc-js/). Do not edit.\nreturn array(\n${Object.entries(data).map(([k, v]) => `\t'${k}' => ${arr(v)},`).join('\n')}\n);\n`);
console.log(Object.fromEntries(Object.entries(data).map(([k, v]) => [k, Object.keys(v).length])));
